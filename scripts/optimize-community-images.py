"""Normalize imported images, then regenerate their content-addressed source maps.

Run after import-community-designs.mjs. Requires Pillow 13.0.0. No dist output.
"""
import hashlib
import io
import json
from pathlib import Path
import re
import subprocess

from PIL import Image, ImageOps, __version__

ROOT = Path(__file__).resolve().parents[1]
DIRECTORY = ROOT / "src/assets/theme-presets/community"
DEFINITIONS = ROOT / "src/shared/community-designs.data.json"
GENERATED = "// Generated by scripts/import-community-designs.mjs and scripts/optimize-community-images.py. Do not edit by hand.\n"


def maximum_dimensions(key, preview_keys, surround_keys):
    if key in preview_keys:
        return (480, 480)
    if key in surround_keys:
        return (1024, 1024)
    return (1920, 1920)


def optimize_image(original, maximum):
    with Image.open(io.BytesIO(original)) as source:
        picture = ImageOps.exif_transpose(source).convert("RGBA" if source.has_transparency_data else "RGB")
        picture.thumbnail(maximum, Image.Resampling.LANCZOS)
        output = io.BytesIO()
        picture.save(output, format="WEBP", quality=82, method=6, exact=True)
    return output.getvalue()


def remap_asset_keys(value, mapping):
    if isinstance(value, str):
        return mapping.get(value, value)
    if isinstance(value, list):
        return [remap_asset_keys(entry, mapping) for entry in value]
    if isinstance(value, dict):
        return {key: remap_asset_keys(entry, mapping) for key, entry in value.items()}
    return value


def remove_unused_images(files):
    retained = {Path(file).name for file in files.values()}
    # Only remove files created by this importer, within its dedicated asset directory.
    for file in DIRECTORY.iterdir():
        if file.is_file() and file.name not in retained and (re.fullmatch(r"[a-f0-9]{64}\.(jpg|png|webp)", file.name) or re.fullmatch(r"\.download-[a-f0-9]{64}\.json", file.name)):
            file.unlink()


def main():
    provenance_path = DIRECTORY / "provenance.json"
    provenance = json.loads(provenance_path.read_text(encoding="utf-8"))
    if provenance.get("imageProcessing"):
        print("Community images already normalized; re-import to normalize a new source snapshot.")
        return
    if __version__ != "13.0.0":
        raise RuntimeError("Use Pillow 13.0.0 for reproducible assets")
    data = json.loads(DEFINITIONS.read_text(encoding="utf-8"))
    presets = [{**data["presetDefaults"], **entry} for entry in data["presets"]]
    surrounds = [{**data["surroundDefaults"], **entry} for entry in data["surrounds"]]
    old_files = data["assets"]
    backgrounds = {key for preset in presets for key in preset["backgroundAssets"].values() if key}
    preview_keys = {preset["previewAssetKey"] for preset in presets} - backgrounds
    surround_keys = {entry["assetKey"] for entry in surrounds} - backgrounds
    mapping, files, details = {}, {}, {}
    before = after = 0
    for key, file in old_files.items():
        original = (ROOT / "src/assets/theme-presets" / file).read_bytes()
        before += len(original)
        optimized = optimize_image(original, maximum_dimensions(key, preview_keys, surround_keys))
        digest = hashlib.sha256(optimized).hexdigest()
        new_key = "community-" + digest[:20]
        filename = digest + ".webp"
        (DIRECTORY / filename).write_bytes(optimized)
        mapping[key] = new_key
        files[new_key] = "community/" + filename
        details[key] = {"assetKey": new_key, "sourceSha256": hashlib.sha256(original).hexdigest(), "sha256": digest, "bytes": len(optimized)}
        after += len(optimized)

    groups = {"presets": remap_asset_keys(presets, mapping), "surrounds": remap_asset_keys(surrounds, mapping), "assets": files}
    subprocess.run(["node", str(ROOT / "scripts/write-community-designs.mjs")], input=json.dumps(groups), text=True, encoding="utf-8", check=True)
    imports = [f'import image{i} from "../assets/theme-presets/{file}";' for i, file in enumerate(files.values())]
    properties = [f'{json.dumps(key)}: image{i}' for i, key in enumerate(files)]
    browser = GENERATED + "\n".join(imports) + "\nexport const COMMUNITY_ASSETS = Object.freeze({\n" + ",\n".join(properties) + "\n});\n"
    (ROOT / "src/shared/community-assets.browser.js").write_text(browser, encoding="utf-8", newline="\n")
    for origin, entry in provenance["assets"].items():
        provenance["assets"][origin] = details[entry["assetKey"]]
    provenance["imageProcessing"] = {"pillow": __version__, "format": "WebP", "quality": 82, "backgroundMaxEdge": 1920, "surroundMaxEdge": 1024, "previewMaxEdge": 480, "originalBytes": before, "optimizedBytes": after}
    provenance_path.write_text(json.dumps(provenance, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")
    remove_unused_images(files)
    print(f"Normalized {len(files)} unique images: {before:,} -> {after:,} bytes")


if __name__ == "__main__":
    main()
