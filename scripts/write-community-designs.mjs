// Shared output for the source importer and image optimizer.
import { readFileSync } from "node:fs";
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const sharedDirectory = fileURLToPath(new URL("../src/shared/", import.meta.url));

function factorEntries(entries) {
  const defaults = {};
  for (const [key, value] of Object.entries(entries[0] || {})) {
    if (entries.every((entry) => Object.hasOwn(entry, key) && JSON.stringify(entry[key]) === JSON.stringify(value))) {
      defaults[key] = value;
    }
  }
  return {
    defaults,
    entries: entries.map((entry) => Object.fromEntries(Object.entries(entry).filter(([key]) => !Object.hasOwn(defaults, key)))),
  };
}

export function createCommunityDesignData({ presets, surrounds, assets }) {
  const presetData = factorEntries(presets);
  const surroundData = factorEntries(surrounds);
  return { presetDefaults: presetData.defaults, presets: presetData.entries,
    surroundDefaults: surroundData.defaults, surrounds: surroundData.entries, assets };
}

export async function writeCommunityDesigns(groups) {
  const data = createCommunityDesignData(groups);
  await writeFile(path.join(sharedDirectory, "community-designs.data.json"), JSON.stringify(data, null, 2) + "\n");
  await writeFile(path.join(sharedDirectory, "community-designs.js"), `// Generated by scripts/write-community-designs.mjs. Do not edit by hand.
import data from "./community-designs.data.json" with { type: "json" };
import { expandCommunityDesignEntries } from "./community-design-data.js";

export const COMMUNITY_PRESETS = expandCommunityDesignEntries(data.presets, data.presetDefaults);
export const COMMUNITY_SURROUNDS = expandCommunityDesignEntries(data.surrounds, data.surroundDefaults);
export const COMMUNITY_ASSET_FILES = Object.freeze(data.assets);
`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  // Python's optimizer sends its transformed metadata through stdin; no upstream code is executed.
  const groups = JSON.parse(readFileSync(0, "utf8"));
  await writeCommunityDesigns(groups);
}
