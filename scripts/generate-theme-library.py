"""Generate bundled thumbnails and a checksum catalogue; originals remain source assets."""
import hashlib
import io
import json
import re
from pathlib import Path

from PIL import Image, ImageOps, __version__

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "src/assets/theme-presets"
GENERATED = "// Generated by scripts/generate-theme-library.py. Do not edit by hand.\n"


def main():
    if __version__ != "13.0.0":
        raise RuntimeError("Use Pillow 13.0.0 for reproducible previews")
    community = json.loads((ROOT / "src/shared/community-designs.data.json").read_text(encoding="utf-8"))["assets"]
    manifest = (ROOT / "src/shared/theme-preset-assets.manifest.js").read_text(encoding="utf-8")
    native = {}
    for line in manifest.splitlines():
        match = re.fullmatch(r' {2}("[\w-]+"|\w+): "([^"\r\n]+)",', line)
        if match:
            native[match[1].strip('"')] = match[2]
    directory = ASSETS / "previews"
    directory.mkdir(exist_ok=True)
    rows = []
    previews = {}
    for key, filename in {**community, **native}.items():
        original = (ASSETS / filename).read_bytes()
        digest = hashlib.sha256(original).hexdigest()
        with Image.open(io.BytesIO(original)) as source:
            mime = Image.MIME[source.format]
            image = ImageOps.exif_transpose(source).convert("RGBA" if source.has_transparency_data else "RGB")
            image.thumbnail((256, 256), Image.Resampling.LANCZOS)
            output = io.BytesIO()
            image.save(output, format="WEBP", quality=65, method=4, exact=True)
        thumbnail = output.getvalue()
        preview = hashlib.sha256(thumbnail).hexdigest() + ".webp"
        (directory / preview).write_bytes(thumbnail)
        rows.append([key, filename, digest, len(original), mime])
        previews[key] = preview
    catalogue = GENERATED
    catalogue += "const rows = " + json.dumps(rows, ensure_ascii=False, separators=(",", ":")) + ";\n"
    catalogue += "export const THEME_ASSET_CATALOG = Object.freeze(Object.fromEntries(rows.map(([key, file, sha256, bytes, mime]) => [key, Object.freeze({ file, sha256, bytes, mime })])));\n"
    (ROOT / "src/shared/theme-asset-catalog.js").write_text(catalogue, encoding="utf-8", newline="\n")
    files = list(dict.fromkeys(previews.values()))
    indices = {file: index for index, file in enumerate(files)}
    browser = GENERATED + "\n".join(f'import p{i} from "../assets/theme-presets/previews/{file}";' for i, file in enumerate(files))
    browser += "\nexport const THEME_PRESET_PREVIEWS = Object.freeze({\n"
    browser += ",\n".join(f'{json.dumps(key)}:p{indices[file]}' for key, file in previews.items()) + "\n});\n"
    (ROOT / "src/shared/theme-previews.browser.js").write_text(browser, encoding="utf-8", newline="\n")
    node = GENERATED + "export const THEME_PREVIEW_FILES = Object.freeze(" + json.dumps(previews, separators=(",", ":")) + ");\n"
    (ROOT / "src/shared/theme-previews.manifest.js").write_text(node, encoding="utf-8", newline="\n")
    print(f"Generated {len(rows)} catalogue entries and {len(files)} bundled thumbnails")


if __name__ == "__main__":
    main()
